// Copies docs/legal-drafts/*.md into src/content/legal-drafts.generated.ts so the administrator can read them in the app.
// Run after editing a draft:  node scripts/sync-legal-drafts.mjs
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'

const dir = 'docs/legal-drafts'
const ORDER = [
  'README',
  'where-legal-text-is-needed',
  'customer-terms',
  'privacy-policy',
  'cookie-and-storage-notice',
  'signature-and-identity-notice',
  'vendor-agreement',
  'rider-agreement',
  'payment-commission-settlement-disclosure',
  'refund-return-dispute-policy',
  'location-and-delivery-proof-notice',
  'acceptable-use-and-safety',
  'account-closure-and-data-requests',
  'legal-review-checklist',
  'nigerian-legal-research',
]
const files = readdirSync(dir)
  .filter((f) => f.endsWith('.md'))
  .map((f) => f.replace(/\.md$/, ''))
const rank = (s) => (ORDER.includes(s) ? ORDER.indexOf(s) : ORDER.length)
files.sort((a, b) => rank(a) - rank(b) || a.localeCompare(b))
const docs = files.map((slug) => {
  const markdown = readFileSync(`${dir}/${slug}.md`, 'utf8')
  const title = (/^#\s+(.+)$/m.exec(markdown)?.[1] ?? slug).replace(/\s*\(draft\)\s*$/i, '')
  return { slug, title, markdown }
})
writeFileSync(
  'src/content/legal-drafts.generated.ts',
  `// GENERATED by scripts/sync-legal-drafts.mjs from docs/legal-drafts. Do not edit by hand.\nexport const LEGAL_DRAFTS: { slug: string; title: string; markdown: string }[] = ${JSON.stringify(docs, null, 2)}\n`,
)
console.log(`${docs.length} drafts written`)
